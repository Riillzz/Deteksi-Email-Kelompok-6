-- Jalankan sekali di Supabase Dashboard > SQL Editor.
-- Aplikasi memakai secret API key di sisi server; jangan pernah kirim key ini ke browser.

create table if not exists public.messages (
    id bigint generated by default as identity primary key,
    tracking_hash text not null unique,
    sender_name text not null,
    sender_email text not null,
    recipient_email text not null,
    subject text not null,
    body text not null,
    predicted_label text not null check (predicted_label in ('SPAM', 'HAM')),
    spam_probability double precision not null check (spam_probability between 0 and 1),
    ham_probability double precision not null check (ham_probability between 0 and 1),
    created_at timestamptz not null default now()
);

create index if not exists idx_messages_label_created
    on public.messages (predicted_label, created_at desc);
create index if not exists idx_messages_created
    on public.messages (created_at desc);

alter table public.messages enable row level security;
-- Sengaja tidak membuat policy untuk anon/authenticated.
-- Hanya backend Streamlit yang memegang secret API key yang boleh mengakses tabel.
revoke all on table public.messages from anon, authenticated;
grant all on table public.messages to service_role;
